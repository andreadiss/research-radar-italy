export function positionCardPresentation(position, fallbackTitle = position.title) {
  const review = reviewedCardCopy.find(({ source }) =>
    source.id === position.id &&
    Object.entries(source).every(([key, value]) => position[key] === value)
  );
  return review
    ? { title: review.title, summary: review.summary, topic: { label: "Descrizione sintetica del bando", text: review.summary } }
    : { title: fallbackTitle, summary: position.summary, topic: positionTopicPresentation(position.title, position.summary) };
}
